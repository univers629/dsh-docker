// bannerLines 按终端尺寸挑选横幅，与 install.sh 的三级降级一致：
// bannerLines 按终端尺寸挑选横幅：并排横幅（11 行）→ 只 DSH 大字（8 行）→ 不画。
//
// 这里比 install.sh 的两级降级多一档。原因是向导的正文可能很长（主菜单十项各带
// 说明就是 20 行），而 dpanel 的横幅只有 6 行、主菜单只有 6 项，那边总能并排显示。
// 若只按宽度二选一，长菜单在窄终端上会直接没有品牌图案。
// room 是减去正文后剩余的行数；选项可见始终优先于图案。
func bannerLines(width, room int) []string {
	const bannerWidth = 71 // 鲸鱼 30 列 + 间隔 2 + DSH 39 列
	if width >= bannerWidth && room >= len(bannerArt)+1 {
		return bannerArt
	}
	if room >= len(wordmarkArt)+1 {
		return wordmarkArt
	}
	return nil
}
