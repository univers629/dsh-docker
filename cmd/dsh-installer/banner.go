// bannerForWidth 按终端宽度挑选横幅。
//
// 只看宽度，不看高度：向导每页的内容是固定的，横幅是品牌标识，宽度放得下就显示。
// 高度不足是压缩横幅行数要解决的问题（见本文件顶部），不是按高度隐藏图案的理由。
func bannerForWidth(width int) []string {
	const bannerWidth = 56 // 并排横幅的实际宽度
	if width >= bannerWidth {
		return bannerArt
	}
	return wordmarkArt
}
